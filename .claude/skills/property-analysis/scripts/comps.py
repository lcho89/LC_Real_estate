"""
comps.py — the URA comps engine behind the Eric Chiew property analysis skill.

Reads the local URA transaction dataset (ura_data.js, generated by fetch_ura_data.py)
and returns the comparable transactions needed to value a subject listing.

Usage
-----
    python comps.py --project "Grand Dunman" --size 1119 --price 2650000 --bedrooms 3
    python comps.py --project "Treasure At Tampines" --bedrooms 3 --months 12
    python comps.py --district D15 --bedrooms 3 --size 1100 --months 12
    python comps.py --list-projects "dunman"

Output is JSON on stdout: four comp tiers plus project vitals.
Add --table for a human-readable summary instead.
"""

