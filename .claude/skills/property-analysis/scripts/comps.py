def bedroom_from_sqft(sqft):
    if sqft <= 430:
        return "Studio"
    if sqft <= 650:
        return "1-Bedroom"
    if sqft <= 970:
        return "2-Bedroom"
    if sqft <= 1300:
        return "3-Bedroom"
    if sqft <= 2000:
        return "4-Bedroom"
    if sqft <= 2800:
        return "5-Bedroom"
    return "Penthouse"


def months_ago(row, cutoff_year, cutoff_month):
    return (row["year"], row["month"]) >= (cutoff_year, cutoff_month)


def cutoff(months):
    today = date.today()
    total = today.year * 12 + (today.month - 1) - months
    return total // 12, (total % 12) + 1


def summarise(rows, label):
    """Median-centred summary of a comp set."""
    if not rows:
        return {"label": label, "n": 0}
    psfs = sorted(r["psf"] for r in rows)
    prices = sorted(r["transactionValue"] for r in rows)
    sizes = sorted(r["size"] for r in rows)
    dates = sorted((r["year"], r["month"]) for r in rows)
    return {
        "label": label,
        "n": len(rows),
        "psf_median": round(statistics.median(psfs)),
        "psf_p25": round(psfs[max(0, int(len(psfs) * 0.25) - 0)]),
        "psf_p75": round(psfs[min(len(psfs) - 1, int(len(psfs) * 0.75))]),
        "psf_min": psfs[0],
        "psf_max": psfs[-1],
        "price_median": round(statistics.median(prices)),
        "size_median": round(statistics.median(sizes)),
        "date_from": f"{dates[0][0]}-{dates[0][1]:02d}",
        "date_to": f"{dates[-1][0]}-{dates[-1][1]:02d}",
        "projects": [p for p, _ in Counter(r["project"] for r in rows).most_common(8)],
    }


def as_transactions(rows, limit=25):
    """The actual prints, newest first — these go into the report table."""
    ordered = sorted(rows, key=lambda r: (r["year"], r["month"]), reverse=True)[:limit]
    return [
        {
            "project": r["project"],
            "date": f"{r['year']}-{r['month']:02d}",
            "size": r["size"],
            "psf": r["psf"],
            "price": r["transactionValue"],
            "floor": r["floorRange"],
            "bedroom": r["bedroomType"],
            "saleType": r["saleType"],
            "district": r["district"],
            "tenure": r.get("tenure"),
        }
        for r in ordered
    ]


def cagr(series):
    """series: {year: median_psf}. Returns compound annual growth over the span."""
    years = sorted(series)
    if len(years) < 2:
        return None
    first, last = years[0], years[-1]
    span = last - first
    if span <= 0 or series[first] <= 0:
        return None
    return round(((series[last] / series[first]) ** (1 / span) - 1) * 100, 2)


def yearly_median_psf(rows):
    buckets = defaultdict(list)
    for r in rows:
        buckets[r["year"]].append(r["psf"])
    return {y: round(statistics.median(v)) for y, v in sorted(buckets.items())}


