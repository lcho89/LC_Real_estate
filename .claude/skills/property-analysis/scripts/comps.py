def repo_root():
    """Walk up from this file to the repo root (three levels up from scripts/)."""
    here = os.path.abspath(os.path.dirname(__file__))
    return os.path.abspath(os.path.join(here, "..", "..", "..", ".."))


def find_data_file(explicit=None):
    if explicit:
        if not os.path.exists(explicit):
            sys.exit(f"Data file not found: {explicit}")
        return explicit
    root = repo_root()
    found = [(os.path.getmtime(p), p)
             for p in (os.path.join(root, rel) for rel in DATA_CANDIDATES)
             if os.path.exists(p)]
    if found:
        return max(found)[1]
    sys.exit(
        "No ura_data.js found. Generate one with:\n"
        "  python fetch_ura_data.py\n"
        "or pass --data <path>."
    )


def load_dataset(path):
    """Load ura_data.js in either the plain or the dictionary-encoded (compact) format.

    Returns (rows_as_dicts, meta) where every row has decoded string values.
    """
    with open(path, encoding="utf-8") as fh:
        raw = fh.read()
    start = raw.index("{")
    end = raw.rindex("}") + 1
    blob = json.loads(raw[start:end])

    cols = blob["cols"]
    meta = blob.get("meta") or {}
    idx = {c: i for i, c in enumerate(cols)}
    rows = []

    for r in blob["rows"]:
        rec = {}
        for col, i in idx.items():
            val = r[i]
            dic = meta.get(col)
            # Compact format stores an integer index into meta[col]
            if dic and isinstance(val, int) and 0 <= val < len(dic):
                val = dic[val]
            rec[col] = val
        rows.append(rec)

    header = raw.split("\n", 1)[0].strip().lstrip("/").strip()
    return rows, {"file": path, "header": header, "count": len(rows)}


